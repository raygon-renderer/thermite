#![allow(unused_imports)]

macro_rules! import_intrinsics {
    ($($name:ident),+ $(,)?) => {
        #[cfg(target_arch = "x86_64")]
        pub use core::arch::x86_64::{$($name),+};

        #[cfg(target_arch = "x86")]
        pub use core::arch::x86::{$($name),+};
    };
}

