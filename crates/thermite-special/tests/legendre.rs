#[test]
fn associated_values_match_the_exact_reference() {
    for &(n, m, ref row) in ASSOC.iter() {
        for (j, &x) in XS.iter().enumerate() {
            // Odd m carries a half power of (1 - x^2); the table holds the rational part.
            let want = if m % 2 == 1 {
                row[j] * (1.0 - x * x).sqrt()
            } else {
                row[j]
            };
            let got = D::splat(x).legendre(n, m).extract::<0>();
            close(&format!("P_{n}^{m}({x})"), got, want, 1e-12);
        }
    }
}

#[test]
fn the_condon_shortley_phase_is_present() {
    // P_1^1(x) = -sqrt(1 - x^2) with the phase, +sqrt(1 - x^2) without it. This single
    // sign is the whole difference between the two conventions in the literature, and a
    // magnitude-only test cannot see it.
    for &x in &XS {
        let got = D::splat(x).legendre(1, 1).extract::<0>();
        let mag = (1.0 - x * x).sqrt();
        close(&format!("P_1^1({x})"), got, -mag, 1e-14);
        assert!(
            got < 0.0,
            "P_1^1({x}) must be negative under Condon-Shortley, got {got}"
        );
    }
}

