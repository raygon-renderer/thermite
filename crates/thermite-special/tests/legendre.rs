// --- P_n(x), the m = 0 case ---

#[test]
fn every_hardcoded_degree_matches_the_exact_reference() {
    // Degrees 1..13 are individually hand-tuned Estrin polynomials with their own literal
    // coefficients, so this is the only test that can see a typo in any single one.
    for (i, row) in LEGENDRE.iter().enumerate().take(13) {
        let n = i as u32 + 1;
        for (j, &x) in XS.iter().enumerate() {
            let got = D::splat(x).legendre(n, 0).extract::<0>();
            close_cond(&format!("P_{n}({x})"), got, row[j], LEGENDRE_COND[i][j], f64::EPSILON);
        }
    }
}

#[test]
fn the_runtime_recurrence_takes_over_cleanly_at_degree_14() {
    // Degrees up to 13 come from the unrolled table; 14 and up are produced by a loop
    // seeded with degrees 12 and 13. A handover that is off by one degree, or that seeds
    // from the wrong pair, shows up here and nowhere else.
    for (i, row) in LEGENDRE.iter().enumerate().skip(13) {
        let n = i as u32 + 1;
        for (j, &x) in XS.iter().enumerate() {
            let got = D::splat(x).legendre(n, 0).extract::<0>();
            close_cond(&format!("P_{n}({x})"), got, row[j], LEGENDRE_COND[i][j], f64::EPSILON);
        }
    }
}

#[test]
fn degree_zero_is_one_everywhere() {
    for &x in &XS {
        assert_eq!(D::splat(x).legendre(0, 0).extract::<0>(), 1.0);
    }
    // Including outside [-1, 1], where P_0 is still identically 1.
    assert_eq!(D::splat(4.5).legendre(0, 0).extract::<0>(), 1.0);
}

#[test]
fn satisfies_the_three_term_recurrence_well_past_the_table() {
    // (n+1) P_{n+1} = (2n+1) x P_n - n P_{n-1}, checked as a residual against the size of
    // the terms rather than of the result: the identity sums to zero, so scaling by the
    // result would measure cancellation instead of the kernel.
    for &x in &[-0.9375, -0.5, -0.125, 0.0, 0.25, 0.625, 0.9375, 1.0, -1.0] {
        let v = D::splat(x);
        for n in 1..40u32 {
            let pm = v.legendre(n - 1, 0).extract::<0>();
            let p0 = v.legendre(n, 0).extract::<0>();
            let pp = v.legendre(n + 1, 0).extract::<0>();

            let a = (n + 1) as f64 * pp;
            let b = (2 * n + 1) as f64 * x * p0;
            let c = n as f64 * pm;

            // The identity sums to zero, so the residual has to be judged against what the
            // three inputs are each entitled to be wrong by, propagated through their own
            // multipliers, not against the (zero) result.
            let bound = f64::EPSILON
                * ((n + 1) as f64 * sigma(n + 1) + (2 * n + 1) as f64 * sigma(n) + n as f64 * sigma(n - 1));

            let residual = a - b + c;
            assert!(
                residual.abs() <= bound,
                "recurrence at n={n}, x={x}: residual {residual:e} > bound {bound:e}"
            );
        }
    }
}

#[test]
fn endpoints_and_parity_are_exact() {
    for n in 0..20u32 {
        // P_n(1) = 1 and P_n(-1) = (-1)^n, both exactly representable.
        close(
            &format!("P_{n}(1)"),
            D::splat(1.0).legendre(n, 0).extract::<0>(),
            1.0,
            1e-14,
        );
        let want = if n % 2 == 0 { 1.0 } else { -1.0 };
        close(
            &format!("P_{n}(-1)"),
            D::splat(-1.0).legendre(n, 0).extract::<0>(),
            want,
            1e-14,
        );

        // P_n(-x) = (-1)^n P_n(x). The Estrin forms are written in x^2 and x^4, so a
        // misplaced odd/even term breaks parity while still matching at some points.
        for &x in &XS {
            let pos = D::splat(x).legendre(n, 0).extract::<0>();
            let neg = D::splat(-x).legendre(n, 0).extract::<0>();
            close(
                &format!("parity P_{n}({x})"),
                neg,
                if n % 2 == 0 { pos } else { -pos },
                1e-13,
            );
        }
    }
}

#[test]
fn odd_degrees_vanish_at_the_origin() {
    // P_n(0) = 0 for odd n, and for even n it is (-1)^{n/2} (n-1)!! / n!!.
    let mut want = 1.0f64;
    for n in 0..16u32 {
        let got = D::splat(0.0).legendre(n, 0).extract::<0>();
        if n % 2 == 1 {
            assert!(got.abs() <= 1e-15, "P_{n}(0) should vanish, got {got:e}");
        } else {
            close(&format!("P_{n}(0)"), got, want, 1e-14);
            // Advance to the next even degree's value: multiply by -(n+1)/(n+2).
            want *= -((n + 1) as f64) / ((n + 2) as f64);
        }
    }
}

#[test]
fn lanes_carrying_different_arguments_stay_independent() {
    // The degree is scalar but x is not, so a kernel that accidentally reduced across
    // lanes (or reused lane 0) would pass every one-lane test above.
    use thermite::backend::scalar::Scalar;
    type D4 = thermite::simd::f64x4<Scalar>;

    let xs = [XS[0], XS[3], XS[6], XS[8]];
    for n in 0..14u32 {
        let got = D4::new(xs).legendre(n, 0);
        for (lane, &x) in xs.iter().enumerate() {
            let want = D::splat(x).legendre(n, 0).extract::<0>();
            close(&format!("P_{n} lane {lane}"), got.as_slice()[lane], want, 1e-14);
        }
    }
}

