#[test]
fn the_associated_form_satisfies_its_own_recurrence_in_n() {
    // (n-m+1) P_{n+1}^m = (2n+1) x P_n^m - (n+m) P_{n-1}^m. This holds under either sign
    // convention, so it checks the recurrence independently of the phase test above.
    for &x in &[-0.6875, -0.3125, 0.125, 0.5, 0.875] {
        let v = D::splat(x);
        for m in 1..5u32 {
            for n in (m + 1)..12u32 {
                let pm = v.legendre(n - 1, m).extract::<0>();
                let p0 = v.legendre(n, m).extract::<0>();
                let pp = v.legendre(n + 1, m).extract::<0>();

                let a = (n - m + 1) as f64 * pp;
                let b = (2 * n + 1) as f64 * x * p0;
                let c = (n + m) as f64 * pm;

                let residual = a - b + c;
                let scale = a.abs().max(b.abs()).max(c.abs()).max(1.0);
                assert!(
                    residual.abs() / scale <= 1e-11,
                    "assoc recurrence n={n} m={m} x={x}: residual {residual:e} scale {scale:e}"
                );
            }
        }
    }
}

// --- legendre_series ---

// Minimal double-double for the forward reference: both the P_k recurrence and the
// accumulation, since the recurrence is itself the cancellation-prone step (the same lesson
// as the Chebyshev test's oracle).
type Dd = (f64, f64);

fn two_sum(a: f64, b: f64) -> Dd {
    let s = a + b;
    let bb = s - a;
    (s, (a - (s - bb)) + (b - bb))
}

fn quick_two_sum(a: f64, b: f64) -> Dd {
    let s = a + b;
    (s, b - (s - a))
}

fn two_prod(a: f64, b: f64) -> Dd {
    let p = a * b;
    (p, a.mul_add(b, -p))
}

fn dd_add(a: Dd, b: Dd) -> Dd {
    let (s, e) = two_sum(a.0, b.0);
    quick_two_sum(s, e + a.1 + b.1)
}

fn dd_mul_f64(a: Dd, b: f64) -> Dd {
    let (p, e) = two_prod(a.0, b);
    quick_two_sum(p, e + a.1 * b)
}

fn dd_div_f64(a: Dd, b: f64) -> Dd {
    let q1 = a.0 / b;
    let (p, e) = two_prod(q1, b);
    let r = ((a.0 - p) - e + a.1) / b;
    quick_two_sum(q1, r)
}

/// `sum c_k P_k(x)` with the recurrence `(k+1) P_{k+1} = (2k+1) x P_k - k P_{k-1}` and the
/// accumulation both in double-double.
fn series_reference(coeffs: &[f64], x: f64) -> f64 {
    let mut prev: Dd = (1.0, 0.0);
    let mut cur: Dd = (x, 0.0);
    let mut sum: Dd = (coeffs[0], 0.0);
    for (k, &c) in coeffs.iter().enumerate().skip(1) {
        sum = dd_add(sum, dd_mul_f64(cur, c));
        // (2k+1) x P_k - k P_{k-1}, then / (k+1)
        let a = dd_mul_f64(dd_mul_f64(cur, (2 * k + 1) as f64), x);
        let b = dd_mul_f64(prev, -(k as f64));
        let next = dd_div_f64(dd_add(a, b), (k + 1) as f64);
        prev = cur;
        cur = next;
    }
    sum.0 + sum.1
}

/// `sum |c_k P_k(x)|`, the scale the summation cancels through.
fn series_condition(coeffs: &[f64], x: f64) -> f64 {
    let (mut prev, mut cur) = (1.0, x);
    let mut s = coeffs[0].abs();
    for (k, &c) in coeffs.iter().enumerate().skip(1) {
        s += (c * cur).abs();
        let next = ((2 * k + 1) as f64 * x * cur - k as f64 * prev) / (k + 1) as f64;
        prev = cur;
        cur = next;
    }
    s
}

const SN: usize = 24;

fn decaying() -> [f64; SN] {
    let mut c = [0.0; SN];
    for (k, slot) in c.iter_mut().enumerate() {
        *slot = if k % 2 == 0 { 1.0 } else { -1.0 } * 0.75f64.powi(k as i32);
    }
    c
}

#[test]
fn series_matches_the_double_double_forward_sum() {
    let c = decaying();
    let xs: Vec<f64> = (-20..=20).map(|i| i as f64 / 20.0).collect();
    for &x in &xs {
        let want = series_reference(&c, x);
        let got = D::splat(x).legendre_series::<SN>(&c).extract::<0>();
        let bound = 4.0 * f64::EPSILON * series_condition(&c, x).max(1.0);
        assert!(
            (got - want).abs() <= bound,
            "series at x={x}: got {got}, want {want} (err {:e} > {bound:e})",
            (got - want).abs()
        );
    }
}

