#[test]
fn series_short_forms() {
    for &x in &XS {
        let v = D::splat(x);
        assert_eq!(v.legendre_series::<1>(&[2.5]).extract::<0>(), 2.5);
        let want = 2.5 - 1.25 * x;
        let got = v.legendre_series::<2>(&[2.5, -1.25]).extract::<0>();
        assert!((got - want).abs() <= 2.0 * f64::EPSILON, "N=2 at {x}");
        // N = 3 is the first to enter the loop-hoist path.
        let want = 2.5 - 1.25 * x + 0.5 * (1.5 * x * x - 0.5);
        let got = v.legendre_series::<3>(&[2.5, -1.25, 0.5]).extract::<0>();
        assert!((got - want).abs() <= 8.0 * f64::EPSILON, "N=3 at {x}: {got} vs {want}");
    }
}

#[test]
fn henyey_greenstein_moments_reproduce_the_closed_form() {
    // p(mu) = (1 - g^2) / (1 + g^2 - 2 g mu)^{3/2} = sum (2l+1) g^l P_l(mu). The Legendre
    // moments of the phase function are (2l+1) g^l. This is the series' headline use in a
    // renderer, and its closed form is an oracle independent of every kernel in this crate.
    //
    // Truncation after N terms is bounded by the tail with |P_l| <= 1 (attained at mu = 1):
    //     sum_{l>=N} (2l+1) |g|^l = |g|^N [ (2N+1)/(1-|g|) + 2|g|/(1-|g|)^2 ]
    const N: usize = 40;
    for &g in &[0.2f64, 0.4, 0.5, -0.3] {
        let mut c = [0.0f64; N];
        for (l, slot) in c.iter_mut().enumerate() {
            *slot = (2 * l + 1) as f64 * g.powi(l as i32);
        }
        let ag = g.abs();
        let trunc = ag.powi(N as i32) * ((2 * N + 1) as f64 / (1.0 - ag) + 2.0 * ag / ((1.0 - ag) * (1.0 - ag)));

        for i in 0..=40 {
            let mu = -1.0 + i as f64 / 20.0;
            let want = (1.0 - g * g) / (1.0 + g * g - 2.0 * g * mu).powf(1.5);
            let got = D::splat(mu).legendre_series::<N>(&c).extract::<0>();
            let bound = trunc + 1e-14 * want.abs().max(1.0);
            assert!(
                (got - want).abs() <= bound,
                "HG g={g} mu={mu}: got {got}, want {want} (err {:e} > {bound:e})",
                (got - want).abs()
            );
        }
    }
}

