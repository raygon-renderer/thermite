#[test]
fn f32_series_tracks_the_reference() {
    let c = decaying();
    let mut c32 = [0.0f32; SN];
    for (o, &v) in c32.iter_mut().zip(c.iter()) {
        *o = v as f32;
    }
    let mut cw = [0.0f64; SN];
    for (o, &v) in cw.iter_mut().zip(c32.iter()) {
        *o = v as f64;
    }
    for i in -16..=16 {
        let x = i as f64 / 16.0;
        let want = series_reference(&cw, x);
        let got = F::splat(x as f32).legendre_series::<SN>(&c32).extract::<0>() as f64;
        let bound = 4.0 * f32::EPSILON as f64 * series_condition(&cw, x).max(1.0);
        assert!(
            (got - want).abs() <= bound,
            "f32 series at x={x}: err {:e} > {bound:e}",
            (got - want).abs()
        );
    }
}

