//! Legendre polynomials: `legendre(n, 0)` and the associated form `legendre(n, m)`.
//!
//! References come from `scripts/legendre_ref.py`, which runs the defining recurrences in
//! exact rational arithmetic (Python `fractions`) at dyadic `x` and rounds to f64 exactly
//! once. The x values are exact in binary64, so the tables carry no floating-point history
//! and the tolerances below measure this kernel rather than an oracle's own drift.
//!
//! Coverage is organized around the four things that can independently go wrong.
//!
//! The hand-tuned Estrin polynomials for degrees 1..13 are each a separate literal
//! coefficient set, so a typo in one degree is invisible from any other. The value table
//! pins every one of them.
//!
//! The runtime recurrence that takes over at degree 14 is a different code path seeded
//! from degrees 12 and 13, so the handover is checked explicitly rather than assumed.
//!
//! The three-term recurrence check is the structural counterpart to the table: it holds
//! for every degree at once, needs no reference values, and runs far past the table's
//! range. A wrong coefficient fails it even at an x the table happens not to sample.
//!
//! The associated form (m > 0) routes through `jacobi` and applies the Condon-Shortley
//! phase itself, so it needs both absolute values and a convention check: the sign of
//! `P_1^1` is exactly what a CS/no-CS mix-up gets wrong.
//!
//! `legendre_series` (Clenshaw over the same recurrence) is covered at the end: against a
//! double-double forward sum, against the single kernel through a unit coefficient, and
//! against the Henyey-Greenstein phase function, whose Legendre-moment expansion has a
//! closed form and is the series' headline application.
#![cfg(any(
    target_arch = "x86",
    target_arch = "x86_64",
    all(target_arch = "wasm32", feature = "wasm"),
    target_arch = "aarch64"
))]

