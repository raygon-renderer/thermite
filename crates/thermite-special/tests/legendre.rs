#[track_caller]
fn close(name: &str, got: f64, want: f64, tol: f64) {
    // Mixed absolute/relative: several probes sit near a root of P_n, where a pure
    // relative bound measures the conditioning of the problem rather than the kernel.
    let err = (got - want).abs() / want.abs().max(1.0);
    assert!(err <= tol, "{name}: got {got:?}, want {want:?} (err {err:e})");
}

/// Assert against the *conditioning* of the evaluation rather than a flat ulp count.
///
/// A monomial-basis evaluation of `P_n` has to cancel through terms of size
/// `sum |c_k| |x|^k`, and for the higher hard-coded degrees that dwarfs the result:
/// `P_12(0.875)` cancels terms of order 2000 down to 0.23, so an honest bound there is
/// about 1e-12, not 1e-16. A flat tolerance is therefore either vacuous at low degree or
/// a false alarm at high degree. `LEGENDRE_COND` carries the exact scale per (n, x), so
/// each degree gets the bound it actually deserves.
#[track_caller]
fn close_cond(name: &str, got: f64, want: f64, cond: f64, eps: f64) {
    let bound = eps * cond.max(1.0);
    let err = (got - want).abs();
    assert!(
        err <= bound,
        "{name}: got {got:?}, want {want:?} (err {err:e} > bound {bound:e})"
    );
}

/// Upper bound on that same conditioning, independent of `x` (valid for `|x| <= 1`).
///
/// Degrees past 13 leave the unrolled Estrin table for a runtime recurrence seeded from
/// degrees 12 and 13, so they inherit the seeds' error but do not keep growing like the
/// monomial sum does. Clamping at 14 keeps the bound valid without letting it explode.
fn sigma(n: u32) -> f64 {
    LEGENDRE_SIGMA[(n as usize).min(LEGENDRE_SIGMA.len() - 1)]
}

