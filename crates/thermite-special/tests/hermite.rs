/// `hermite` takes its degree as a const generic, so the sweep has to be unrolled.
macro_rules! for_each_degree {
    ($mac:ident) => {
        $mac!(1);
        $mac!(2);
        $mac!(3);
        $mac!(4);
        $mac!(5);
        $mac!(6);
        $mac!(7);
        $mac!(8);
        $mac!(9);
        $mac!(10);
        $mac!(11);
        $mac!(12);
    };
}

#[test]
fn every_degree_matches_the_exact_reference() {
    macro_rules! check {
        ($n:literal) => {
            for (j, &x) in XS.iter().enumerate() {
                let got = D::splat(x).hermite_n::<$n>().extract::<0>();
                close_cond(
                    &format!("H_{}({x})", $n),
                    got,
                    HERMITE[$n - 1][j],
                    HERMITE_COND[$n - 1][j],
                    f64::EPSILON,
                );
            }
        };
    }
    for_each_degree!(check);
}

#[test]
fn degree_zero_is_one() {
    for &x in &XS {
        assert_eq!(D::splat(x).hermite_n::<0>().extract::<0>(), 1.0);
    }
}

/// Degrees for which `n - 1`, `n` and `n + 1` all have table rows. Kept separate from
/// `for_each_degree!` on purpose: a runtime `if n + 1 <= 12` inside the full sweep still
/// *compiles* the out-of-range index for the top degree, which is a real out-of-bounds
/// expression that only a never-taken branch hides.
macro_rules! for_each_interior_degree {
    ($mac:ident) => {
        $mac!(2);
        $mac!(3);
        $mac!(4);
        $mac!(5);
        $mac!(6);
        $mac!(7);
        $mac!(8);
        $mac!(9);
        $mac!(10);
        $mac!(11);
    };
}

#[test]
fn satisfies_the_two_term_recurrence() {
    // H_{n+1} = 2x H_n - 2n H_{n-1}, as a residual against the size of the terms. This is
    // the structural counterpart to the value table: it needs no reference at all, and it
    // fails at any x if a single degree's coefficients are wrong.
    macro_rules! check {
        ($n:literal) => {
            for (j, &x) in XS.iter().enumerate() {
                let v = D::splat(x);
                let hm = HERMITE[$n - 2][j];
                let h0 = v.hermite_n::<$n>().extract::<0>();
                let hp = v.hermite_n::<{ $n + 1 }>().extract::<0>();

                let residual = hp - 2.0 * x * h0 + 2.0 * ($n as f64) * hm;
                let bound = f64::EPSILON
                    * (HERMITE_COND[$n][j]
                        + 2.0 * x.abs() * HERMITE_COND[$n - 1][j]
                        + 2.0 * ($n as f64) * HERMITE_COND[$n - 2][j]);
                assert!(
                    residual.abs() <= bound,
                    "recurrence at n={}, x={x}: residual {residual:e} > bound {bound:e}",
                    $n
                );
            }
        };
    }
    for_each_interior_degree!(check);
}

#[test]
fn parity_follows_the_degree() {
    // H_n(-x) = (-1)^n H_n(x). The recurrence mixes x and n, so a sign slip in the
    // `2n H_{n-1}` term breaks parity while still matching at x = 0.
    macro_rules! check {
        ($n:literal) => {
            for &x in &XS {
                let pos = D::splat(x).hermite_n::<$n>().extract::<0>();
                let neg = D::splat(-x).hermite_n::<$n>().extract::<0>();
                let want = if $n % 2 == 0 { pos } else { -pos };
                assert!(
                    (neg - want).abs() <= 1e-9 * pos.abs().max(1.0),
                    "parity H_{}({x}): got {neg}, want {want}",
                    $n
                );
            }
        };
    }
    for_each_degree!(check);
}

#[test]
fn values_at_the_origin_match_the_closed_form() {
    // H_n(0) = 0 for odd n, and (-2)^{n/2} (n-1)!! for even n.
    assert_eq!(D::splat(0.0).hermite_n::<0>().extract::<0>(), 1.0);

    macro_rules! check {
        ($n:literal) => {{
            let got = D::splat(0.0).hermite_n::<$n>().extract::<0>();
            if $n % 2 == 1 {
                assert!(got.abs() <= 1e-12, "H_{}(0) should vanish, got {got:e}", $n);
            } else {
                // (-2)^{n/2} * (n-1)!!
                let mut want = 1.0f64;
                let mut k = 1i64;
                while k < $n {
                    want *= -2.0 * k as f64;
                    k += 2;
                }
                assert!(
                    (got - want).abs() <= 1e-9 * want.abs(),
                    "H_{}(0): got {got}, want {want}",
                    $n
                );
            }
        }};
    }
    for_each_degree!(check);
}

#[test]
fn lanes_carrying_different_arguments_stay_independent() {
    use thermite::backend::scalar::Scalar;
    type D4 = thermite::simd::f64x4<Scalar>;

    let xs = [XS[0], XS[3], XS[6], XS[8]];
    macro_rules! check {
        ($n:literal) => {{
            let got = D4::new(xs).hermite_n::<$n>();
            for (lane, &x) in xs.iter().enumerate() {
                let want = D::splat(x).hermite_n::<$n>().extract::<0>();
                assert_eq!(got.as_slice()[lane], want, "H_{} lane {lane} at x={x}", $n);
            }
        }};
    }
    for_each_degree!(check);
}

