//! Physicists' Hermite polynomials: `hermite_n::<N>` at a const degree.
//!
//! `laguerre.rs` already checks that `hermitev` agrees with `hermite` lane by lane, but
//! that is a consistency check between two kernels: a `hermite` that is simply wrong
//! passes it. These are the absolute values it was missing.
//!
//! References come from `scripts/legendre_ref.py`, which runs `H_{n+1} = 2x H_n - 2n H_{n-1}`
//! in exact rational arithmetic at dyadic `x` and rounds to f64 exactly once.
//!
//! Tolerances are scaled by `sum |c_k| |x|^k` rather than being flat. Hermite coefficients
//! grow fast and alternate, so the cancellation is severe well before the top of this
//! table: `H_9(0.75)` cancels terms totalling 69450 down to -1050. A flat ulp bound would
//! be a false alarm at high degree and vacuous at low degree.
//!
//! The orthonormal Hermite *functions* are covered separately in `hermite_function.rs`.
#![cfg(any(
    target_arch = "x86",
    target_arch = "x86_64",
    all(target_arch = "wasm32", feature = "wasm"),
    target_arch = "aarch64"
))]

use thermite::prelude::*;
use thermite_special::SpecialMath;

type D = Vector<f64>;
type F = Vector<f32>;

#[track_caller]
fn close_cond(name: &str, got: f64, want: f64, cond: f64, eps: f64) {
    let bound = eps * cond.max(1.0);
    let err = (got - want).abs();
    assert!(
        err <= bound,
        "{name}: got {got:?}, want {want:?} (err {err:e} > bound {bound:e})"
    );
}

