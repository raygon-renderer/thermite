//! The Airy functions of **complex argument** (`special` feature), over the whole plane.
//!
//! Two sectors: `K`/`I` at `zeta` for `|ph z| <= 2pi/3`, `J`/`Y` at `-z` in the wedge around
//! the negative axis. The reference is mpmath (`airy_reference.py`, which regenerates
//! `ROWS`). The identities below are independent of it.

#![cfg(feature = "special")]
#![allow(clippy::excessive_precision)]

use thermite::math::policy::policies::Precision;
use thermite::prelude::*;
use thermite_special::SpecialMathWithPolicy;

use thermite_complex::Complex;

type V = Vector<f64>;
type C = Complex<V>;

fn c(re: f64, im: f64) -> C {
    Complex::new(V::splat(re), V::splat(im))
}

fn parts(z: C) -> (f64, f64) {
    (z.re.extract::<0>(), z.im.extract::<0>())
}

fn mag(z: C) -> f64 {
    let (re, im) = parts(z);
    re.hypot(im)
}

/// Complex relative error, `|got - want| / |want|`.
fn rel(got: C, want: (f64, f64)) -> f64 {
    let (gr, gi) = parts(got);
    let (wr, wi) = want;
    let err = ((gr - wr).powi(2) + (gi - wi).powi(2)).sqrt();
    let m = (wr * wr + wi * wi).sqrt();
    if m == 0.0 { err } else { err / m }
}

fn rel_c(got: C, want: C) -> f64 {
    rel(got, parts(want))
}

fn scaled(z: C) -> (C, C, C, C) {
    z.airy_all_p::<Precision, true>()
}

fn plain(z: C) -> (C, C, C, C) {
    z.airy_all_p::<Precision, false>()
}

/// The principal `zeta = (2/3) z sqrt(z)`.
fn zeta(z: C) -> C {
    (z * z.sqrt()) * V::splat(2.0 / 3.0)
}

