/// Every row of the mpmath grid, all four scaled functions, one tolerance.
#[test]
fn scaled_airy_matches_mpmath_over_the_plane() {
    const TOL: f64 = 2e-12;

    let names = ["eAi", "eAip", "eBi", "eBip"];
    let mut worst = [(0.0f64, 0.0, 0.0); 4];
    let mut failures = 0usize;

    for &(re, im, ar, ai, pr, pi, br, bi, qr, qi) in ROWS {
        let z = c(re, im);
        let (a, ap, b, bp) = scaled(z);
        let got = [a, ap, b, bp];
        let want = [(ar, ai), (pr, pi), (br, bi), (qr, qi)];

        for k in 0..4 {
            let e = rel(got[k], want[k]);
            if e > worst[k].0 {
                worst[k] = (e, re, im);
            }
            if !(e <= TOL) {
                failures += 1;
                eprintln!(
                    "{} z = {re} + {im}i: rel {e:e}, got {:?} want {:?}",
                    names[k],
                    parts(got[k]),
                    want[k]
                );
            }
        }
    }

    for k in 0..4 {
        eprintln!(
            "worst {}: {:e} at z = {} + {}i",
            names[k], worst[k].0, worst[k].1, worst[k].2
        );
    }
    assert_eq!(failures, 0, "{failures} cells over {TOL:e}");
}

/// `Ai Bi' - Ai' Bi = 1/pi` everywhere. In the scaled forms the products carry
/// `e^{zeta - |Re zeta|}`, a bounded factor, so the identity can be graded over the whole
/// plane. It is graded against the products' size because the difference is what is left
/// after they cancel.
#[test]
fn the_wronskian_holds_over_the_plane() {
    let pts = [
        (0.3, 0.2),
        (0.0, 1.5),
        (2.0, 3.0),
        (7.0, -2.0),
        (30.0, 40.0),
        (-1.0, 0.5),
        (-4.0, -7.0),
        (-60.0, 20.0),
        (-9.0, 0.0),
        (-0.5, 0.86),
        (-0.5, -0.86),
    ];
    for &(re, im) in &pts {
        let z = c(re, im);
        let (a, ap, b, bp) = scaled(z);
        let (p1, p2) = (a * bp, ap * b);
        let zt = zeta(z);
        let want = (zt - V::splat(parts(zt).0.abs())).exp() * V::FRAC_1_PI;
        let e = mag(p1 - p2 - want) / mag(want).max(mag(p1));
        assert!(e <= 1e-13, "Wronskian at z = {re} + {im}i: rel {e:e}");
    }
}

/// On the real axis the complex route agrees with the real kernel on both sides. The real
/// crate leaves the oscillating side unscaled, so only the unscaled forms are compared.
#[test]
fn the_real_axis_agrees_with_the_real_kernel() {
    for x in [-40.0, -9.0, -2.5, -0.7, -1e-3, 0.0, 1e-3, 0.4, 2.0, 7.0, 30.0, 90.0] {
        let z = c(x, 0.0);
        let (a, ap, b, bp) = plain(z);
        let (ra, rap, rb, rbp) = V::splat(x).airy_all_p::<Precision, false>();
        let want = [
            ra.extract::<0>(),
            rap.extract::<0>(),
            rb.extract::<0>(),
            rbp.extract::<0>(),
        ];
        let got = [a, ap, b, bp];
        let names = ["Ai", "Ai'", "Bi", "Bi'"];
        for k in 0..4 {
            let (gr, gi) = parts(got[k]);
            // The oscillating side is graded against its envelope, like the real tests.
            let env = if x < 0.0 {
                (-x).powf(if k % 2 == 0 { -0.25 } else { 0.25 }) / core::f64::consts::PI.sqrt()
            } else {
                0.0
            };
            let scale = want[k].abs().max(env);
            // The real kernel's own unscaled error is `zeta eps / 2` (its docs), which is
            // what the tolerance follows.
            let tol = 1e-13 * (1.0 + mag(zeta(z)));
            assert!(
                (gr - want[k]).abs() <= tol * scale,
                "{}({x}): {gr} vs {}",
                names[k],
                want[k]
            );
            assert!(
                gi.abs() <= tol * scale,
                "{}({x}) must be real: {:?}",
                names[k],
                parts(got[k])
            );
        }
    }
}

/// The seam between the two sectors, the rays at `+-2pi/3`: the two routes must agree
/// where they meet, at every radius.
#[test]
fn the_two_sectors_agree_across_their_seam() {
    for r in [0.5, 2.0, 10.0, 40.0] {
        for sign in [1.0, -1.0] {
            let inside = 119.999_f64.to_radians() * sign;
            let outside = 120.001_f64.to_radians() * sign;
            let zi = c(r * inside.cos(), r * inside.sin());
            let zo = c(r * outside.cos(), r * outside.sin());
            let (a, ap, b, bp) = scaled(zi);
            let (oa, oap, ob, obp) = scaled(zo);
            // The functions themselves move across the seam by the distance times the
            // derivative (in the scaled forms the scaling moves too, by |zeta| dz), so the
            // check is continuity to that order: no jump beyond what the derivative
            // explains. The rows at 119.9, 120.0 and 120.1 degrees in the mpmath grid are
            // the accuracy check on the seam. This is the coarser sanity check on it.
            let dz = mag(zo - zi);
            let allowed = |v: C, d: C| dz * (mag(d) + mag(zeta(zi)) * mag(v)) * 2.0 + 1e-11 * mag(v);
            assert!(
                mag(a - oa) <= allowed(a, ap),
                "Ai seam at r = {r}, sign {sign}: {:?} vs {:?}",
                parts(a),
                parts(oa)
            );
            assert!(
                mag(b - ob) <= allowed(b, bp),
                "Bi seam at r = {r}, sign {sign}: {:?} vs {:?}",
                parts(b),
                parts(ob)
            );
            let _ = (oap, obp);
        }
    }
}

/// The origin and its neighbourhood, and NaN.
#[test]
fn the_origin_is_exact() {
    let (a, ap, b, bp) = plain(c(0.0, 0.0));
    assert_eq!(parts(a), (0.3550280538878172, 0.0));
    assert_eq!(parts(ap), (-0.2588194037928068, 0.0));
    assert_eq!(parts(b), (0.6149266274460007, 0.0));
    assert_eq!(parts(bp), (0.4482883573538264, 0.0));

    for &(re, im) in &[(1e-220, 1e-220), (-1e-215, 0.0), (0.0, 1e-300)] {
        let (za, _, zb, _) = scaled(c(re, im));
        assert_eq!(parts(za), parts(a), "Ai({re} + {im}i) must be Ai(0)");
        assert_eq!(parts(zb), parts(b), "Bi({re} + {im}i) must be Bi(0)");
    }

    let (a, _, _, _) = plain(c(f64::NAN, 0.0));
    assert!(parts(a).0.is_nan());
}

/// The unscaled forms are the scaled ones times their exponentials.
#[test]
fn the_unscaled_forms_agree_with_the_scaled_ones() {
    for &(re, im) in &[
        (0.7, 0.4),
        (0.0, 5.0),
        (12.0, -6.0),
        (-8.0, 3.0),
        (-3.0, -3.0),
        (20.0, 20.0),
    ] {
        let z = c(re, im);
        let zt = zeta(z);
        let (a, ap, b, bp) = plain(z);
        let (sa, sap, sb, sbp) = scaled(z);
        let e_mz = (-zt).exp();
        let e_re = V::splat(parts(zt).0.abs().exp());
        for (name, got, want) in [
            ("Ai", a, sa * e_mz),
            ("Ai'", ap, sap * e_mz),
            ("Bi", b, sb * e_re),
            ("Bi'", bp, sbp * e_re),
        ] {
            assert!(
                rel_c(got, want) <= 1e-14,
                "{name}({re} + {im}i): {:?} vs {:?}",
                parts(got),
                parts(want)
            );
        }
    }
}

/// A packet with a different sector in every lane agrees with the lanes evaluated alone.
#[test]
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
fn a_mixed_packet_agrees_with_its_lanes() {
    use thermite::backend::x86_v3::X86V3;

    type W = Vector<<X86V3 as Simd>::f64x4>;
    type CW = Complex<W>;

    let re = W::splat(0.5).insert::<1>(-3.0).insert::<2>(8.0).insert::<3>(-12.0);
    let im = W::splat(0.3).insert::<1>(4.0).insert::<2>(-5.0).insert::<3>(-1.0);
    let z = CW::new(re, im);
    let (a, ap, b, bp) = z.airy_all_p::<Precision, true>();

    for lane in 0..4 {
        let zl = c(re.extractv(lane), im.extractv(lane));
        let (wa, wap, wb, wbp) = scaled(zl);
        for (got, want) in [(a, wa), (ap, wap), (b, wb), (bp, wbp)] {
            let g = c(got.re.extractv(lane), got.im.extractv(lane));
            assert!(
                rel_c(g, want) <= 1e-15,
                "lane {lane}: {:?} vs {:?}",
                parts(g),
                parts(want)
            );
        }
    }
}
