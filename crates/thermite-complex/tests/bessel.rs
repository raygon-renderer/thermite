//! Bessel functions of **complex argument** and real order (`special` feature).
//!
//! `I`, `K`, `J`, `Y`, `H^(1)`, `H^(2)` over the whole plane, by the real-order `I`/`K` kernel
//! from `thermite-special` run in complex arithmetic on the right half-plane, plus the
//! rotations and continuations that build the rest. The reference is mpmath at 40 digits
//! (`bessel_reference.py`, which regenerates `ROWS`). The identities below are independent
//! of it.

#![cfg(feature = "special")]
#![allow(clippy::excessive_precision)]

use thermite::math::policy::policies::Precision;
use thermite::prelude::*;
use thermite_complex::math::special::ComplexSpecialMathWithPolicy;
use thermite_complex::math::special::{H1, H2};
use thermite_special::bessel::{I, J, K, Scaled, Y};
use thermite_special::{BesselOrder, SpecialMathWithPolicy};

use thermite_complex::Complex;

type V = Vector<f64>;
type C = Complex<V>;
type S = <C as GenericVector>::Signed;

fn c(re: f64, im: f64) -> C {
    Complex::new(V::splat(re), V::splat(im))
}

fn parts(z: C) -> (f64, f64) {
    (z.re.extract::<0>(), z.im.extract::<0>())
}

fn real(nu: f64) -> BesselOrder<C, S> {
    BesselOrder::Real(c(nu, 0.0))
}

fn realv(nu: f64) -> BesselOrder<V, <V as GenericVector>::Signed> {
    BesselOrder::Real(V::splat(nu))
}

/// The six functions in their SciPy scalings.
fn ie(nu: f64, z: C) -> C {
    z.bessel_p::<Precision, Scaled<I>>(real(nu))
}

fn ke(nu: f64, z: C) -> C {
    z.bessel_p::<Precision, Scaled<K>>(real(nu))
}

fn je(nu: f64, z: C) -> C {
    z.bessel_p::<Precision, Scaled<J>>(real(nu))
}

fn ye(nu: f64, z: C) -> C {
    z.bessel_p::<Precision, Scaled<Y>>(real(nu))
}

fn h1e(nu: f64, z: C) -> C {
    z.hankel_p::<Precision, Scaled<H1>>(realv(nu))
}

fn h2e(nu: f64, z: C) -> C {
    z.hankel_p::<Precision, Scaled<H2>>(realv(nu))
}

/// Complex relative error, `|got - want| / |want|`.
fn rel(got: C, want: (f64, f64)) -> f64 {
    let (gr, gi) = parts(got);
    let (wr, wi) = want;
    let err = ((gr - wr).powi(2) + (gi - wi).powi(2)).sqrt();
    let mag = (wr * wr + wi * wi).sqrt();
    if mag == 0.0 { err } else { err / mag }
}

fn rel_c(got: C, want: C) -> f64 {
    rel(got, parts(want))
}

