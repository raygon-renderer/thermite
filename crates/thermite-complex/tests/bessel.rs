/// Every row of the mpmath grid, all six families, one tolerance. The worst row per family
/// is printed so a regression shows up as a number rather than as a failed assert alone.
#[test]
fn all_six_families_match_mpmath_over_the_plane() {
    const TOL: f64 = 1e-12;

    let names = ["ive", "kve", "jve", "yve", "h1e", "h2e"];
    let mut worst = [(0.0f64, 0.0, 0.0, 0.0); 6];
    let mut failures = 0usize;

    for &(nu, re, im, ir, ii, kr, ki, jr, ji, yr, yi, ar, ai, br, bi) in ROWS {
        let z = c(re, im);
        let got = [ie(nu, z), ke(nu, z), je(nu, z), ye(nu, z), h1e(nu, z), h2e(nu, z)];
        let want = [(ir, ii), (kr, ki), (jr, ji), (yr, yi), (ar, ai), (br, bi)];

        for k in 0..6 {
            let e = rel(got[k], want[k]);
            if e > worst[k].0 {
                worst[k] = (e, nu, re, im);
            }
            if !(e <= TOL) {
                failures += 1;
                eprintln!(
                    "{} nu = {nu}, z = {re} + {im}i: rel {e:e}, got {:?} want {:?}",
                    names[k],
                    parts(got[k]),
                    want[k]
                );
            }
        }
    }

    for k in 0..6 {
        eprintln!(
            "worst {}: {:e} at nu = {}, z = {} + {}i",
            names[k], worst[k].0, worst[k].1, worst[k].2, worst[k].3
        );
    }
    assert_eq!(failures, 0, "{failures} cells over {TOL:e}");
}

/// `J_{nu+1} Y_nu - J_nu Y_{nu+1} = 2/(pi z)` and `I_nu K_{nu+1} + I_{nu+1} K_nu = 1/z`, in
/// the scaled forms (each product's exponentials cancel). Independent of mpmath.
#[test]
fn the_wronskians_hold_over_the_plane() {
    let pts = [
        (0.3, 0.2),
        (0.0, 1.5),
        (2.0, 3.0),
        (7.0, -2.0),
        (0.0, 30.0),
        (50.0, 40.0),
        (200.0, 0.1),
        (-1.0, 0.5),
        (-4.0, -7.0),
        (-60.0, 20.0),
    ];
    for &(re, im) in &pts {
        for nu in [0.0, 1.0 / 3.0, 0.5, 2.25, 6.0, -0.75] {
            let z = c(re, im);
            // `ive * kve = I K e^{z - |Re z|}`: the two SciPy scalings do not cancel, but
            // leave a unit rotation on the right and `e^{2 Re z}` on the left.
            // Graded against the products' size: on the left half-plane `K` is dominated by
            // its `i pi I` continuation term, so the two products cancel by `e^{2 Re w}` and
            // the Wronskian is what the small `K` term leaves behind.
            let (q1, q2) = (ie(nu, z) * ke(nu + 1.0, z), ie(nu + 1.0, z) * ke(nu, z));
            let w_ik = q1 + q2;
            let want = (C::ONE / z) * (z - V::splat(re.abs())).exp();
            let mag = |c: C| parts(c).0.hypot(parts(c).1);
            let e = mag(w_ik - want) / mag(want).max(mag(q1));
            assert!(e <= 1e-13, "I/K Wronskian at nu = {nu}, z = {re} + {im}i: rel {e:e}");

            // The oscillating pair's Wronskian in the Hankel form, `H1_{nu+1} H2_nu - H1_nu
            // H2_{nu+1} = -4i/(pi z)`, whose scaled products carry no exponential at all. The
            // `J`/`Y` form cancels to `e^{-2|Im z|}` off the axis and cannot be graded there.
            // Graded against the products' own size: near the origin at high order both
            // products are `~1/z^{2 nu + 1}` and the Wronskian is what is left after they
            // cancel, so a relative grade against `4/(pi z)` measures the conditioning of
            // the identity rather than the functions.
            let p1 = h1e(nu + 1.0, z) * h2e(nu, z);
            let p2 = h1e(nu, z) * h2e(nu + 1.0, z);
            let w_h = p1 - p2;
            let want = Complex::new(V::ZERO, -(V::FRAC_2_PI + V::FRAC_2_PI)) / z;
            let d = w_h - want;
            let mag = |c: C| parts(c).0.hypot(parts(c).1);
            let e = mag(d) / mag(want).max(mag(p1));
            assert!(e <= 1e-13, "Hankel Wronskian at nu = {nu}, z = {re} + {im}i: rel {e:e}");
        }
    }
}

/// `H1 + H2 = 2J` and `H1 - H2 = 2iY`, unscaled, where nothing overflows.
#[test]
fn the_hankel_pair_combines_to_j_and_y() {
    for &(re, im) in &[
        (0.7, 0.4),
        (0.0, 5.0),
        (12.0, -6.0),
        (-3.0, 2.0),
        (-20.0, -1.0),
        (30.0, 0.0),
    ] {
        for nu in [1.0 / 3.0, 2.25, -0.75, 4.0] {
            let z = c(re, im);
            let h1 = z.hankel_p::<Precision, H1>(realv(nu));
            let h2 = z.hankel_p::<Precision, H2>(realv(nu));
            let j = z.bessel_p::<Precision, J>(real(nu));
            let y = z.bessel_p::<Precision, Y>(real(nu));
            // Graded against the larger operand: near the origin at high order both Hankel
            // functions are `~1/z^nu` while `J` is `~z^nu`, so `H1 + H2` cancels to something
            // far below either term and a relative grade against `2J` would be meaningless.
            let big = |a: C, b: C| parts(a).0.hypot(parts(a).1).max(parts(b).0.hypot(parts(b).1));
            let two_j = h1 + h2;
            let two_iy = h1 - h2;
            let i_two_y = Complex::new(-(y.im + y.im), y.re + y.re);
            let (d1, d2) = (two_j - (j + j), two_iy - i_two_y);
            assert!(
                parts(d1).0.hypot(parts(d1).1) <= 1e-13 * big(h1, h2),
                "H1 + H2 vs 2J at nu = {nu}, z = {re} + {im}i"
            );
            assert!(
                parts(d2).0.hypot(parts(d2).1) <= 1e-13 * big(h1, h2),
                "H1 - H2 vs 2iY at nu = {nu}, z = {re} + {im}i"
            );
        }
    }
}

/// On the positive real axis every family must agree with the real kernels, to a few ulp
/// and with an imaginary part no larger than the second asymptotic term leaves.
#[test]
fn the_positive_real_axis_agrees_with_the_real_kernels() {
    for x in [0.1, 0.9, 2.0, 2.5, 7.0, 25.0, 45.0, 120.0, 800.0] {
        for nu in [1.0 / 3.0, 0.5, 2.25, 7.4, -1.0 / 3.0, -2.5] {
            let order = realv(nu);
            let z = c(x, 0.0);
            let want_i = V::splat(x).bessel_p::<Precision, Scaled<I>>(order).extract::<0>();
            let want_k = V::splat(x).bessel_p::<Precision, Scaled<K>>(order).extract::<0>();
            let want_j = V::splat(x).bessel_p::<Precision, J>(order).extract::<0>();
            let want_y = V::splat(x).bessel_p::<Precision, Y>(order).extract::<0>();

            let checks = [
                ("I", ie(nu, z), want_i),
                ("K", ke(nu, z), want_k),
                ("J", je(nu, z), want_j),
                ("Y", ye(nu, z), want_y),
            ];
            for (name, got, want) in checks {
                // J and Y are graded against the envelope sqrt(2/pi x), since they have zeros.
                let scale = if name == "J" || name == "Y" {
                    want.abs().max((2.0 / (core::f64::consts::PI * x)).sqrt())
                } else {
                    want.abs()
                };
                // I and K agree with the real kernel to a few ulp. J and Y do not, and the
                // complex route is the one that is right: at `nu = 7.4, x = 2.5` the real
                // Steed arm returns `Y = -120.8499078725141` against mpmath's
                // `-120.84990787442137` (1.6e-11), while this path is within 1e-15. Steed is
                // run at the full order there, and loses digits once `nu` is well above `x`.
                // Recorded in `notes/special`. The tolerance here is the real kernel's.
                let tol = if name == "J" || name == "Y" { 1e-10 } else { 4e-14 };
                let (gr, gi) = parts(got);
                assert!((gr - want).abs() <= tol * scale, "{name}_{nu}({x}): {gr} vs {want}");
                // I and K rotate by exactly (1, 0) on the axis, while J and Y go through two
                // unit rotations whose product rounds and leaves an imaginary residue of an
                // ulp. The residue is an ulp of the O(1) Hankel intermediate, not of the result.
                let imag_tol = if name == "J" || name == "Y" {
                    4e-15 * scale.max(1.0)
                } else {
                    1e-30 * scale
                };
                assert!(gi.abs() <= imag_tol, "{name}_{nu}({x}) must be real: {:?}", parts(got));
            }
        }
    }
}

/// `K_{-nu} = K_nu` exactly, everywhere: the kernel evaluates at `|nu|` and `K` needs no
/// reflection, and the continuation is even in `nu` too.
#[test]
fn k_is_even_in_order() {
    for &(re, im) in &[(0.5, 0.5), (0.0, 4.0), (10.0, -3.0), (60.0, 60.0), (-2.0, 1.0)] {
        for nu in [1.0 / 3.0, 0.75, 2.25, 5.5] {
            let z = c(re, im);
            // Bit-exact on the right half-plane, where the kernel evaluates at |nu| and K
            // needs no reflection. On the left the continuation's `I` term enters with the
            // signed order, so the two sides are equal only in exact arithmetic.
            if re >= 0.0 {
                assert_eq!(parts(ke(nu, z)), parts(ke(-nu, z)), "K_{nu} vs K_-{nu} at {re} + {im}i");
            } else {
                assert!(
                    rel_c(ke(nu, z), ke(-nu, z)) <= 1e-14,
                    "K_{nu} vs K_-{nu} at {re} + {im}i"
                );
            }
        }
    }
}

/// The branch cut on the negative real axis: `-0.0` on the imaginary part takes the lower
/// side, and for real order the two sides are conjugates.
#[test]
fn the_negative_real_axis_is_a_branch_cut_with_signed_zero() {
    for x in [0.5, 3.0, 20.0] {
        for nu in [1.0 / 3.0, 2.25, -0.75] {
            let above = c(-x, 0.0);
            let below = c(-x, -0.0);
            for (name, f) in [("I", ie as fn(f64, C) -> C), ("K", ke), ("J", je), ("Y", ye)] {
                let (a, b) = (parts(f(nu, above)), parts(f(nu, below)));
                assert!(
                    (a.0 - b.0).abs() <= 1e-13 * (a.0.abs() + 1.0) && (a.1 + b.1).abs() <= 1e-13 * (a.1.abs() + 1.0),
                    "{name}_{nu}(-{x}) above {a:?} vs below {b:?}"
                );
            }
            // Whole orders have no cut: I and J are single-valued there. The two sides still
            // go through opposite Hankel rotations, so the imaginary part is zero only up to
            // an ulp of the O(1) intermediate, and it flips sign with the side. Bound that
            // residue absolutely rather than as a share of |J_2|, which a complex relative
            // error turns into a 2-ulp swing that lands differently per ISA.
            let (a, b) = (parts(je(2.0, above)), parts(je(2.0, below)));
            assert!(
                (a.0 - b.0).abs() <= 1e-15 * (a.0.abs() + 1.0) && (a.1 - b.1).abs() <= 4e-15,
                "J_2 has no cut: {a:?} vs {b:?}"
            );
        }
    }
}

